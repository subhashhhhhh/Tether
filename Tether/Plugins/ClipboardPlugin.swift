import AppKit
import Combine
import Foundation

public final class ClipboardPlugin: ObservableObject, TetherPlugin, @unchecked Sendable {
    /// The last few things each device sent, newest first: its clipboard and
    /// text shared from it. Kept across launches.
    @Published public private(set) var received: [String: [String]] = [:] {
        didSet { UserDefaults.standard.set(received, forKey: Self.receivedKey) }
    }
    static let receivedLimit = 3
    private static let receivedKey = "tether_received_clipboard"

    public let supportedPacketTypes = [
        "kdeconnect.clipboard",
        "kdeconnect.clipboard.connect"
    ]

    private var lastChangeCount: Int = 0
    private var lastReceivedContent: String = ""
    private var lastSentContent: String = ""
    /// When this Mac's clipboard last changed, to tell whether the phone's
    /// clip on connect is newer. It starts at launch: a clip from before
    /// Tether started mustn't replace what's on this Mac.
    private var lastLocalClipboardTimestamp = Int64(Date().timeIntervalSince1970 * 1000)
    private var timer: Timer?
    private var activeConnections: [DeviceConnection] = []
    private let lock = NSLock()

    static let privateTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    public init() {
        self.received = UserDefaults.standard.dictionary(forKey: Self.receivedKey) as? [String: [String]] ?? [:]
        self.lastChangeCount = NSPasteboard.general.changeCount
        if let initial = NSPasteboard.general.string(forType: .string), !initial.isEmpty {
            self.lastSentContent = initial
        }
    }

    /// macOS has no clipboard-changed notification, so the change count is
    /// polled. Only while a device is there to send to.
    private func updateMonitoring() {
        DispatchQueue.main.async {
            let wanted = !self.lock.withLock { self.activeConnections.isEmpty }
            if wanted, self.timer == nil {
                // Catch up silently: a copy made while nobody was connected
                // isn't sent the moment a phone appears.
                self.lastChangeCount = NSPasteboard.general.changeCount
                let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
                    self?.checkPasteboard()
                }
                timer.tolerance = 0.2
                RunLoop.main.add(timer, forMode: .common)
                self.timer = timer
            } else if !wanted, let timer = self.timer {
                timer.invalidate()
                self.timer = nil
            }
        }
    }

    private func checkPasteboard() {
        let currentCount = NSPasteboard.general.changeCount
        guard currentCount != lastChangeCount else { return }
        lastChangeCount = currentCount

        // Password managers mark what they copy; it never leaves this Mac.
        // See nspasteboard.org.
        let types = NSPasteboard.general.types ?? []
        guard !types.contains(where: Self.privateTypes.contains) else { return }

        guard let text = NSPasteboard.general.string(forType: .string), !text.isEmpty else { return }

        // Suppress echo if this content originated from remote device or was already sent
        if Self.isEcho(text, lastReceived: lastReceivedContent, lastSent: lastSentContent) {
            return
        }

        lastSentContent = text
        lastLocalClipboardTimestamp = Int64(Date().timeIntervalSince1970 * 1000)
        TetherLog("[ClipboardPlugin] Local clipboard changed (\(text.count) characters); sending to paired devices")
        broadcastClipboard(content: text)
    }

    public func onConnected(connection: DeviceConnection) {
        guard let deviceId = connection.peerDeviceInfo?.deviceId,
              let paired = TrustStore.shared.pairedDevice(for: deviceId),
              paired.isClipboardSyncEnabled else {
            return
        }

        lock.withLock {
            activeConnections.removeAll { $0.peerDeviceInfo?.deviceId == deviceId }
            activeConnections.append(connection)
        }
        updateMonitoring()
    }

    public func onDisconnected(connection: DeviceConnection) {
        lock.withLock {
            activeConnections.removeAll { $0 === connection }
        }
        updateMonitoring()
    }

    public func handlePacket(connection: DeviceConnection, packet: NetworkPacket) {
        guard packet.type == "kdeconnect.clipboard" || packet.type == "kdeconnect.clipboard.connect" else { return }

        guard let deviceId = connection.peerDeviceInfo?.deviceId,
              let paired = TrustStore.shared.pairedDevice(for: deviceId),
              let content = packet.string(for: "content"), !content.isEmpty else {
            return
        }

        // Whatever the phone copied is kept, so it can be copied here later,
        // even when it doesn't replace this Mac's clipboard.
        remember(content, from: deviceId)
        guard paired.isClipboardSyncEnabled else { return }

        // If it's a connect packet, verify timestamp to prevent overwriting with stale content
        if packet.type == "kdeconnect.clipboard.connect",
           Self.isStale(connectTimestamp: packet.int64(for: "timestamp", default: 0), localChange: lastLocalClipboardTimestamp) {
            TetherLog("[ClipboardPlugin] Ignoring the phone's clip from before this Mac's last change")
            return
        }

        guard !Self.isEcho(content, lastReceived: lastReceivedContent, lastSent: lastSentContent) else { return }

        lastReceivedContent = content
        lastSentContent = content
        if packet.type == "kdeconnect.clipboard.connect" {
            let packetTime = packet.int64(for: "timestamp", default: 0)
            if packetTime > 0 {
                lastLocalClipboardTimestamp = packetTime
            }
        } else {
            lastLocalClipboardTimestamp = Int64(Date().timeIntervalSince1970 * 1000)
        }

        DispatchQueue.main.async {
            NSPasteboard.general.clearContents()
            NSPasteboard.general.setString(content, forType: .string)
            self.lastChangeCount = NSPasteboard.general.changeCount
            TetherLog("[ClipboardPlugin] Synced clipboard (\(content.count) characters) from \(connection.peerDeviceInfo?.deviceName ?? "Device")")
        }
    }

    /// Text the phone shared with this Mac: put on the clipboard, kept with
    /// what the phone copied, and not sent back to it.
    public func acceptShared(_ text: String, from deviceId: String) {
        remember(text, from: deviceId)
        lastReceivedContent = text
        lastSentContent = text
        lastLocalClipboardTimestamp = Int64(Date().timeIntervalSince1970 * 1000)
        DispatchQueue.main.async {
            NSPasteboard.general.clearContents()
            NSPasteboard.general.setString(text, forType: .string)
            self.lastChangeCount = NSPasteboard.general.changeCount
        }
    }

    private func remember(_ content: String, from deviceId: String) {
        DispatchQueue.main.async {
            let history = self.received[deviceId] ?? []
            let updated = Self.adding(content, to: history)
            if updated != history { self.received[deviceId] = updated }
        }
    }

    /// The history with this at the front, once, kept to the limit.
    static func adding(_ content: String, to history: [String]) -> [String] {
        var history = history
        history.removeAll { $0 == content }
        history.insert(content, at: 0)
        return Array(history.prefix(receivedLimit))
    }

    /// Text that came from a device, or was just sent to one, isn't a new copy.
    static func isEcho(_ text: String, lastReceived: String, lastSent: String) -> Bool {
        text == lastReceived || text == lastSent
    }

    /// The phone's clip on connect is older than this Mac's last change.
    static func isStale(connectTimestamp: Int64, localChange: Int64) -> Bool {
        connectTimestamp > 0 && connectTimestamp < localChange
    }

    /// Puts something a device sent earlier back on this Mac's clipboard,
    /// without sending it to the devices again.
    public func copyReceived(_ content: String) {
        lastSentContent = content
        NSPasteboard.general.clearContents()
        NSPasteboard.general.setString(content, forType: .string)
        lastChangeCount = NSPasteboard.general.changeCount
    }

    /// Sends text to one device, as Send Clipboard does.
    public func send(_ content: String, to connection: DeviceConnection) {
        lastSentContent = content
        connection.send(packet: NetworkPacket(type: "kdeconnect.clipboard", body: ["content": content]))
    }

    public func broadcastClipboard(content: String) {
        let packet = NetworkPacket(
            type: "kdeconnect.clipboard",
            body: ["content": content]
        )
        let targets: [DeviceConnection] = lock.withLock { activeConnections }
        for connection in targets {
            if let deviceId = connection.peerDeviceInfo?.deviceId,
               let paired = TrustStore.shared.pairedDevice(for: deviceId),
               paired.isClipboardSyncEnabled {
                connection.send(packet: packet)
            }
        }
    }
}
